import { afterEach, describe, expect, it, vi } from 'vitest'
import { createSimulationController, simulationMetadata } from './simulation-controller.js'

const create = (seed) => ({ seed, records: [{ incident_id: `baseline-${seed}` }], step: 0, asOf: '2026-09-21T00:00:00-04:00' })
const advance = (s, scenario) => ({ ...s, step: s.step + 1, asOf: `step-${s.step + 1}`,
  records: [...s.records, { incident_id: `${s.seed}-${s.step + 1}-${scenario}` }] })
const response = (req) => ({ meta: { is_mock: false, reviewed_zones: req.reviewed_zones, as_of: req.as_of }, marker: req.records.at(-1).incident_id })
function setup(analyze = vi.fn(async (req) => response(req)), extra = {}) {
  const c = createSimulationController({ analyze, create, advance, maxSteps: 3, ...extra })
  c.setActive(true)
  return { c, analyze }
}
const deferred = () => { let resolve, reject; const promise = new Promise((a, b) => { resolve = a; reject = b }); return { promise, resolve, reject } }
afterEach(() => { vi.useRealTimers() })

describe('simulation requests and successful snapshots', () => {
  it('starts unreviewed; review retains the clock and records; reset clears confirmations', async () => {
    const { c, analyze } = setup()
    await c.reset(5300)
    const rows = c.getSnapshot().session.records
    await c.review('A')
    expect(analyze.mock.calls[1][0].as_of).toBe('2026-09-21T00:00:00-04:00')
    expect(c.getSnapshot().session.records).toBe(rows)
    expect(c.getSnapshot().result.meta.reviewed_zones).toEqual(['A'])
    await c.reset(2)
    expect(c.getSnapshot().result.meta.reviewed_zones).toEqual([])
    expect(c.getSnapshot().schedule).toEqual([])
    c.cancel()
  })
  it('failed step retains the snapshot and retries exactly the same candidate', async () => {
    const analyze = vi.fn(async (req) => response(req))
    const { c } = setup(analyze)
    await c.reset(1)
    const before = c.getSnapshot()
    analyze.mockRejectedValueOnce(new Error('offline'))
    expect(await c.advance()).toBe(false)
    expect(c.getSnapshot().session).toBe(before.session)
    expect(c.getSnapshot().result).toBe(before.result)
    expect(c.getSnapshot().error).toBe('offline')
    await c.advance()
    expect(analyze.mock.calls[2][0]).toEqual(analyze.mock.calls[1][0])
    c.cancel()
  })
  it('ignores an old response after reset even if transport ignores abort', async () => {
    const old = deferred()
    const analyze = vi.fn().mockReturnValueOnce(old.promise).mockImplementation(async (req) => response(req))
    const { c } = setup(analyze)
    const first = c.reset(1)
    await Promise.resolve()
    await c.reset(2)
    old.resolve({ meta: { is_mock: false, reviewed_zones: [], as_of: 'old' } })
    await first
    expect(c.getSnapshot().session.seed).toBe(2)
    expect(c.getSnapshot().result.marker).toBe('baseline-2')
    c.cancel()
  })
  it('rejects mock output and invalid seed without replacing successful state', async () => {
    const analyze = vi.fn(async (req) => response(req))
    const { c } = setup(analyze)
    await c.reset(1)
    analyze.mockResolvedValueOnce({ meta: { is_mock: true } })
    expect(await c.advance()).toBe(false)
    expect(c.getSnapshot().session.step).toBe(0)
    expect(c.getSnapshot().error).toMatch(/mock/)
    expect(await c.reset(-1)).toBe(false)
    expect(analyze).toHaveBeenCalledTimes(2)
    c.cancel()
  })
  it('changes only future scenario records and exports the replay schedule', async () => {
    const { c } = setup()
    await c.reset(1); await c.advance()
    const previous = c.getSnapshot().session.records
    c.setScenario('zone_shift'); await c.advance()
    expect(c.getSnapshot().session.records.slice(0, previous.length)).toEqual(previous)
    expect(simulationMetadata(c.getSnapshot()).scenario_schedule).toEqual([
      { from_step: 1, scenario: 'normal' }, { from_step: 2, scenario: 'zone_shift' },
    ])
    c.cancel()
  })
})

describe('bounded serial playback', () => {
  it('requires pause before a baseline review and starts without a stale paused-error label', async () => {
    vi.useFakeTimers()
    const analyze = vi.fn(async (req) => response(req))
    const { c } = setup(analyze)
    await c.reset(1)
    analyze.mockRejectedValueOnce(new Error('offline'))
    await c.advance()
    c.start()
    expect(c.getSnapshot().error).toBe('')
    expect(await c.review('A')).toBe(false)
    expect(analyze).toHaveBeenCalledTimes(2)
    c.pause()
    await c.review('A')
    await vi.advanceTimersByTimeAsync(5000)
    expect(analyze).toHaveBeenCalledTimes(3)
    expect(c.getSnapshot().result.meta.reviewed_zones).toEqual(['A'])
    c.cancel()
  })
  it('waits for the previous analysis before scheduling another step', async () => {
    vi.useFakeTimers()
    const wait = deferred()
    const analyze = vi.fn(async (req) => response(req))
    const { c } = setup(analyze)
    await c.reset(1)
    analyze.mockReturnValueOnce(wait.promise)
    c.setDelay(500); c.start()
    await vi.advanceTimersByTimeAsync(500)
    await vi.advanceTimersByTimeAsync(2000)
    expect(analyze).toHaveBeenCalledTimes(2)
    expect(c.getSnapshot().session.step).toBe(0)
    wait.resolve(response(analyze.mock.calls[1][0]))
    await vi.advanceTimersByTimeAsync(0)
    await vi.advanceTimersByTimeAsync(499)
    expect(analyze).toHaveBeenCalledTimes(2)
    await vi.advanceTimersByTimeAsync(501)
    expect(c.getSnapshot().session.step).toBe(3)
    expect(c.getSnapshot().running).toBe(false)
    c.cancel()
  })
  it('pauses and cancels a pending step when navigation leaves the tab', async () => {
    const wait = deferred()
    const analyze = vi.fn(async (req) => response(req))
    const { c } = setup(analyze)
    await c.reset(1)
    analyze.mockReturnValueOnce(wait.promise)
    const pending = c.advance()
    await Promise.resolve()
    c.setActive(false)
    expect(analyze.mock.calls[1][1].signal.aborted).toBe(true)
    wait.resolve(response(analyze.mock.calls[1][0])); await pending
    expect(c.getSnapshot().session.step).toBe(0)
    expect(c.getSnapshot().running).toBe(false)
    expect(c.getSnapshot().busy).toBe(false)
  })
  it('times out, aborts transport, and retains the last successful snapshot', async () => {
    vi.useFakeTimers()
    const analyze = vi.fn(async (req) => response(req))
    const { c } = setup(analyze)
    await c.reset(1)
    analyze.mockReturnValueOnce(new Promise(() => {}))
    const pending = c.advance()
    await vi.advanceTimersByTimeAsync(15000)
    expect(await pending).toBe(false)
    expect(analyze.mock.calls[1][1].signal.aborted).toBe(true)
    expect(c.getSnapshot().session.step).toBe(0)
    expect(c.getSnapshot().error).toMatch(/timed out/)
    c.cancel()
  })
})
